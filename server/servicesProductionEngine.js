/**
 * Evaluates Office, Corporate, Financial & High-Tech Services production.
 * Unlike agriculture or mining (which face diminishing land/resource returns),
 * knowledge and corporate services exhibit increasing super-linear returns to scale:
 * Y_corp = L_corp * w_base * (H/50)^1.10 * (A/50)^1.15 * (1 + F/100) * (1 + 0.5 * D/100)
 */
export function calculateSuperLinearAgglomeration({
  humanCapital = 50,
  urbanAgglom = 50,
  financeDepth = 50,
  digitalConn = 50,
  labor = 1000000,
  baseWage = 52000,
  productivityScaler = 2.85,
}) {
  const normH = Math.max(1, Number(humanCapital) || 50) / 50;
  const normA = Math.max(1, Number(urbanAgglom) || 50) / 50;
  const normF = Math.max(0, Number(financeDepth) || 50) / 100;
  const normD = Math.max(0, Number(digitalConn) || 50) / 100;

  // Elasticity exponents
  const ALPHA_TALENT = 1.10; // Human capital / STEM skills
  const BETA_AGGLOM = 1.15;  // Urban density & knowledge spillovers (super-linear)

  const talentMultiplier = Math.pow(normH, ALPHA_TALENT);
  const agglomMultiplier = Math.pow(normA, BETA_AGGLOM);
  const financeMultiplier = 1.0 + normF;
  const digitalMultiplier = 1.0 + 0.5 * normD;

  const compoundAgglomeration =
    talentMultiplier * agglomMultiplier * financeMultiplier * digitalMultiplier;

  // Output: labor * effective worker productivity
  const workerProductivity = baseWage * compoundAgglomeration * productivityScaler;
  const corporateOutput = Math.max(0, labor * workerProductivity);

  // Wage premium generated by agglomeration surplus passed to knowledge workers
  const wagePremiumRate = Math.max(0, (compoundAgglomeration - 1.0) * 0.28);

  return {
    corporateOutput,
    compoundAgglomeration,
    workerProductivity,
    talentMultiplier,
    agglomMultiplier,
    financeMultiplier,
    digitalMultiplier,
    effectiveTechProductivity: talentMultiplier * digitalMultiplier,
    financeCapacityMultiplier: financeMultiplier,
    wagePremiumRate,
    superLinearExponent: BETA_AGGLOM,
  };
}

/**
 * Evaluates Hospitality, Tourism, Entertainment & Consumer Services.
 * Scales with population, local disposable income, and consumer amenities,
 * with sub-linear elasticity (0.85) and crime dampening.
 * Y_consumer = L_cons * w_base * (C/50)^0.85 * (SoL/50)^0.50 * (1 - crimeRate/200)
 */
export function calculateConsumerServices({
  consumerAmenity = 50,
  labor = 500000,
  baseWage = 42000,
  sol = 50,
  crimeRate = 15,
  productivityScaler = 1.65,
}) {
  const normC = Math.max(1, Number(consumerAmenity) || 50) / 50;
  const normSol = Math.max(1, Number(sol) || 50) / 50;

  const GAMMA_AMENITY = 0.85; // Sub-linear local amenity elasticity
  const DELTA_SOL = 0.50;     // Standard of Living purchasing power elasticity

  const amenityMultiplier = Math.pow(normC, GAMMA_AMENITY);
  const solMultiplier = Math.pow(normSol, DELTA_SOL);

  // Crime penalty: higher crime depresses tourist visitation and retail activity
  const clampedCrime = Math.max(0, Math.min(80, Number(crimeRate) || 15));
  const crimeDampening = Math.max(0.60, Math.min(1.0, 1.0 - clampedCrime / 200));

  const hospitalityDemandMultiplier = amenityMultiplier * solMultiplier * crimeDampening;
  const workerProductivity = baseWage * hospitalityDemandMultiplier * productivityScaler;
  const consumerOutput = Math.max(0, labor * workerProductivity);

  return {
    consumerOutput,
    amenityMultiplier,
    solMultiplier,
    crimeDampening,
    hospitalityDemandMultiplier,
    workerProductivity,
    subLinearExponent: GAMMA_AMENITY,
  };
}

/**
 * Evaluates comprehensive services production for an endowment profile.
 */
export function evaluateServicesProduction({
  endowment,
  employedLabor = 1000000,
  baseWage = 48000,
  sol = 50,
  crimeRate = 15,
  productivityScaler = 1.0,
}) {
  const h = endowment?.humanCapitalIndex ?? 50;
  const a = endowment?.urbanAgglomerationIndex ?? 50;
  const f = endowment?.financialDepthIndex ?? 50;
  const d = endowment?.digitalConnectivityIndex ?? 50;
  const c = endowment?.consumerAmenityIndex ?? 50;

  // Endogenous labor partitioning between Corporate/Office and Hospitality/Consumer
  // Higher urban/finance/tech endowments shift labor share towards corporate services
  const knowledgeWeight = (h + a + f + d) / 4;
  const consumerWeight = c;
  const corporateShare = Math.max(
    0.58,
    Math.min(0.78, (knowledgeWeight * 2.2) / (knowledgeWeight * 2.2 + consumerWeight))
  );

  const corpLabor = Math.round(employedLabor * corporateShare);
  const consumerLabor = Math.max(0, employedLabor - corpLabor);

  const corporate = calculateSuperLinearAgglomeration({
    humanCapital: h,
    urbanAgglom: a,
    financeDepth: f,
    digitalConn: d,
    labor: corpLabor,
    baseWage: baseWage * 1.15, // Higher baseline knowledge wage
    productivityScaler: productivityScaler * 1.25,
  });

  const consumer = calculateConsumerServices({
    consumerAmenity: c,
    labor: consumerLabor,
    baseWage: baseWage * 0.85, // Retail and hospitality service wage
    sol,
    crimeRate,
    productivityScaler: productivityScaler * 0.95,
  });

  const totalServicesGdp = corporate.corporateOutput + consumer.consumerOutput;
  const corporateGdpShare = totalServicesGdp > 0 ? corporate.corporateOutput / totalServicesGdp : 0;
  const consumerGdpShare = totalServicesGdp > 0 ? consumer.consumerOutput / totalServicesGdp : 0;

  // Identify top strategic specializations
  const specializations = [];
  if (f >= 75) specializations.push("Commercial Banking & Asset Management");
  if (h >= 75 && d >= 75) specializations.push("High-Tech Software & Cloud Compute");
  if (h >= 80) specializations.push("Biomedical & Quantum R&D");
  if (c >= 75) specializations.push("Tier-1 Hospitality & Tourism Attraction");
  if (a >= 80) specializations.push("Megalopolis Corporate Headquarters");
  if (specializations.length === 0) {
    specializations.push("Regional Commerce & Professional Services");
  }

  const aiAdvisoryContext = [
    `Human Capital: ${h}% (STEM & Universities)`,
    `Urban Agglomeration: ${a}% (Metropolitan density & network scale)`,
    `Financial Depth: ${f}% (Banking assets & venture funds)`,
    `Digital Infrastructure: ${d}% (Cloud data centers & gigabit fiber)`,
    `Consumer Amenities: ${c}% (Tourism, recreation & hospitality)`,
    `Super-Linear Scaling Multiplier: ${corporate.compoundAgglomeration.toFixed(2)}x`,
    `Hospitality Demand Multiplier: ${consumer.hospitalityDemandMultiplier.toFixed(2)}x`,
    `Corporate Services Share: ${(corporateGdpShare * 100).toFixed(1)}%`,
    `Hospitality Share: ${(consumerGdpShare * 100).toFixed(1)}%`,
    `Primary Specializations: ${specializations.join("; ")}`,
  ].join("\n");

  return {
    corporate,
    consumer,
    totalServicesGdp,
    corporateGdpShare,
    consumerGdpShare,
    corporateShareOfLabor: corporateShare,
    specializations,
    aiAdvisoryContext,
    indices: {
      humanCapitalIndex: h,
      urbanAgglomerationIndex: a,
      financialDepthIndex: f,
      digitalConnectivityIndex: d,
      consumerAmenityIndex: c,
    },
  };
}

/**
 * Evaluates state services breakdown for any US state.
 */
export function evaluateStateServices(stateName, totalStateLabor = 3000000, stateTotalGdp = 200000000000) {
  const endowment = getUsStateServicesEndowment(stateName);
  // In modern US economy, ~78% of workers are in service sectors
  const servicesLabor = Math.round(totalStateLabor * 0.78);

  // Calibrate scaling factor to match state target empirical GDP share (~70-75% services)
  const targetServicesGdp = stateTotalGdp * 0.72;
  const rawEval = evaluateServicesProduction({
    endowment,
    employedLabor: servicesLabor,
    baseWage: 54000,
    sol: 60,
    crimeRate: 15,
  });

  const scaleRatio = targetServicesGdp > 0 && rawEval.totalServicesGdp > 0
    ? targetServicesGdp / rawEval.totalServicesGdp
    : 1.0;

  return {
    stateName: endowment.name,
    stateCode: endowment.code,
    region: endowment.region,
    indices: {
      humanCapitalIndex: endowment.humanCapitalIndex,
      urbanAgglomerationIndex: endowment.urbanAgglomerationIndex,
      financialDepthIndex: endowment.financialDepthIndex,
      digitalConnectivityIndex: endowment.digitalConnectivityIndex,
      consumerAmenityIndex: endowment.consumerAmenityIndex,
    },
    clusters: endowment.primaryClusters || [],
    servicesProfile: endowment.servicesProfile || {},
    modeledServicesOutput: endowment.modeledServicesOutput,
    sourceAttribution: endowment.sourceAttribution,
    totalServicesGdp: targetServicesGdp,
    corporateServicesGdp: rawEval.corporate.corporateOutput * scaleRatio,
    hospitalityServicesGdp: rawEval.consumer.consumerOutput * scaleRatio,
    corporateGdpShare: rawEval.corporateGdpShare,
    consumerGdpShare: rawEval.consumerGdpShare,
    specializations: rawEval.specializations,
    aiAdvisoryContext: rawEval.aiAdvisoryContext,
  };
}
