/**
 * Returns geographic endowments for a neighbouring province (e.g. Canadian province or Mexican state).
 */
export function getNeighbourProvinceEndowments(name) {
  if (!name) return null;
  const p = NEIGHBOUR_PROVINCES[name];
  if (p) return p;

  // Case-insensitive lookup
  const clean = name.toLowerCase().trim();
  for (const [k, v] of Object.entries(NEIGHBOUR_PROVINCES)) {
    if (k.toLowerCase() === clean) return v;
  }
  return null;
}
