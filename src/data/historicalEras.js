// Helper to find closest historical era for any given date string or numeric year
export function getHistoricalEraForDate(dateStrOrYear) {
  let yr = 2015;
  if (typeof dateStrOrYear === "number") {
    yr = dateStrOrYear;
  } else if (typeof dateStrOrYear === "string") {
    const clean = dateStrOrYear.trim();
    if (clean.startsWith("-")) {
      yr = -parseInt(clean.slice(1).split("-")[0], 10);
    } else {
      yr = parseInt(clean.split("-")[0], 10) || 2015;
    }
  }

  if (yr <= -200) return HISTORICAL_ERAS[0]; // 500 BC
  if (yr <= 400) return HISTORICAL_ERAS[1];  // 117 AD
  if (yr <= 1400) return HISTORICAL_ERAS[2]; // 1000 AD
  if (yr <= 1800) return HISTORICAL_ERAS[3]; // 1776
  if (yr <= 1900) return HISTORICAL_ERAS[4]; // 1836
  if (yr <= 1950) return HISTORICAL_ERAS[5]; // 1939
  return HISTORICAL_ERAS[6];                 // 2015 Modern
}

